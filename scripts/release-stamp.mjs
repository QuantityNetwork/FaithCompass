#!/usr/bin/env node
/**
 * Writes the production release identity (commit SHA and deployment id) into the docs, between
 *   <!-- release:begin --> ... <!-- release:end -->
 * in docs/RELEASE_BLOCKERS.md and docs/FINAL_PRODUCT_CLOSURE.md, so the header is never hand-written.
 *
 * Sources, in order of preference:
 *   --from-status <origin>      GET <origin>/api/v1/status and read `release` (VERCEL_GIT_COMMIT_SHA and
 *                               VERCEL_DEPLOYMENT_ID as seen by the serving deployment). Use after each deploy.
 *   --from-vercel-json <file>   The JSON of a Vercel "list deployments" call (target production); the newest READY
 *                               production deployment is used. For deployments that predate the status field.
 *   --check                     Exit 1 unless both docs carry a generated block (CI).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const DOCS = ['docs/RELEASE_BLOCKERS.md', 'docs/FINAL_PRODUCT_CLOSURE.md'];
const BLOCK = /<!-- release:begin -->[\s\S]*?<!-- release:end -->/;

function block(r) {
  return [
    '<!-- release:begin -->',
    `<!-- Generated by scripts/release-stamp.mjs from ${r.source} at ${r.checked_at}. Do not edit by hand. -->`,
    `**Production release:** commit \`${r.commit_sha.slice(0, 7)}\` (\`${r.commit_sha}\`${r.commit_ref ? `, branch \`${r.commit_ref}\`` : ''}), deployment \`${r.deployment_id}\`. Source: ${r.source}, checked ${r.checked_at}.`,
    '<!-- release:end -->',
  ].join('\n');
}

async function fromStatus(origin) {
  const res = await fetch(`${origin.replace(/\/+$/, '')}/api/v1/status`);
  if (!res.ok) throw new Error(`status HTTP ${res.status}`);
  const r = (await res.json()).release;
  if (!r?.commit_sha || !r?.deployment_id) throw new Error('the status response has no release.commit_sha / release.deployment_id');
  return { commit_sha: r.commit_sha, commit_ref: r.commit_ref, deployment_id: r.deployment_id, source: `${origin}/api/v1/status (release)` };
}

function fromVercelJson(file) {
  const text = readFileSync(file, 'utf8');
  const json = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
  const list = json.result?.deployments?.deployments ?? json.deployments ?? [];
  const d = list.filter((x) => x.target === 'production' && (x.state ?? x.readyState) === 'READY').sort((a, b) => b.created - a.created)[0];
  if (!d) throw new Error('no READY production deployment in the file');
  return { commit_sha: d.meta.githubCommitSha, commit_ref: d.meta.githubCommitRef, deployment_id: d.id ?? d.uid, source: 'Vercel API, list deployments (target production)' };
}

const [flag, arg] = process.argv.slice(2);
if (flag === '--check') {
  const missing = DOCS.filter((f) => !/<!-- release:begin -->\n<!-- Generated by scripts\/release-stamp\.mjs/.test(readFileSync(f, 'utf8')));
  if (missing.length) {
    console.error(`No generated release block in: ${missing.join(', ')}`);
    process.exit(1);
  }
  console.log('Release blocks present.');
} else {
  const r = flag === '--from-status' ? await fromStatus(arg) : flag === '--from-vercel-json' ? fromVercelJson(arg) : null;
  if (!r) {
    console.error('Usage: release-stamp.mjs --from-status <origin> | --from-vercel-json <file> | --check');
    process.exit(2);
  }
  r.checked_at = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
  for (const f of DOCS) {
    const text = readFileSync(f, 'utf8');
    if (!BLOCK.test(text)) throw new Error(`${f} has no release block markers`);
    writeFileSync(f, text.replace(BLOCK, block(r)));
  }
  console.log(`Stamped ${r.commit_sha.slice(0, 7)} / ${r.deployment_id}`);
}
